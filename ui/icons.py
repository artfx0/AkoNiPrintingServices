_SVG_WRAPPER = """<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="{stroke_width}" stroke-linecap="round" stroke-linejoin="round">{path}</svg>"""


def get_svg_content(name: str, color: str = "#64748B", stroke_width: float = 2.0) -> str:
    """Return raw XML string for the specified icon."""
    path = SVG_PATHS.get(name, SVG_PATHS["info"])
    return _SVG_WRAPPER.format(color=color, stroke_width=stroke_width, path=path)


def get_pixmap(
    name: str,
    color: str = "#64748B",
    size: int = 20,
    stroke_width: float = 2.0,
) -> QPixmap:
    """Render an SVG icon into a high-DPI transparent QPixmap."""
    svg_str = get_svg_content(name, color=color, stroke_width=stroke_width)
    renderer = QSvgRenderer(QByteArray(svg_str.encode("utf-8")))

    # Render at 2x scaling for ultra-sharp high-DPI displays
    scale = 2
    pixmap = QPixmap(size * scale, size * scale)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
    renderer.render(painter)
    painter.end()

    # Scale back down with smooth transformation
    return pixmap.scaled(
        size,
        size,
        Qt.AspectRatioMode.KeepAspectRatio,
        Qt.TransformationMode.SmoothTransformation,
    )


def get_icon(
    name: str,
    color: str = "#64748B",
    size: int = 20,
    stroke_width: float = 2.0,
) -> QIcon:
    """Generate a QIcon from the vector SVG definition."""
    pixmap = get_pixmap(name, color=color, size=size, stroke_width=stroke_width)
    return QIcon(pixmap)


def get_nav_icon(name: str, size: int = 18) -> QIcon:
    """Generate a state-aware QIcon for sidebar navigation items."""
    icon = QIcon()
    # Inactive state: neutral slate
    icon.addPixmap(get_pixmap(name, color="#64748B", size=size), QIcon.Mode.Normal, QIcon.State.Off)
    # Selected state: rich amber-gold matching active row
    icon.addPixmap(get_pixmap(name, color="#92400E", size=size), QIcon.Mode.Selected, QIcon.State.Off)
    icon.addPixmap(get_pixmap(name, color="#92400E", size=size), QIcon.Mode.Selected, QIcon.State.On)
    # Active/Hovered: dark navy
    icon.addPixmap(get_pixmap(name, color="#0F172A", size=size), QIcon.Mode.Active, QIcon.State.Off)
    return icon


def get_action_icon(name: str, tone: str = "secondary", size: int = 16) -> QIcon:
    """Generate a state-aware QIcon for action buttons."""
    palette = {
        "primary": ("#0F172A", "#000000"),        # Gold buttons have dark text
        "secondary": ("#475569", "#0F172A"),      # Secondary outline buttons
        "danger": ("#DC2626", "#991B1B"),         # Destructive buttons
        "success": ("#16A34A", "#15803D"),        # Success / verify buttons
        "accent": ("#D4AF37", "#B45309"),         # Gold accent
        "blue": ("#2563EB", "#1D4ED8"),           # Info / links
        "muted": ("#94A3B8", "#64748B"),          # Placeholder / disabled
    }
    normal_col, active_col = palette.get(tone, ("#475569", "#0F172A"))
    icon = QIcon()
    icon.addPixmap(get_pixmap(name, color=normal_col, size=size), QIcon.Mode.Normal)
    icon.addPixmap(get_pixmap(name, color=active_col, size=size), QIcon.Mode.Active)
    return icon

